const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('anvil', {
  listarPlugins: () => ipcRenderer.invoke('plugins:listar'),
  abrirPastaPlugins: () => ipcRenderer.invoke('plugins:abrirPasta'),
  abrir: () => ipcRenderer.invoke('arquivo:abrir'),
  ler: (caminho, lembrar = false) => ipcRenderer.invoke('arquivo:ler', caminho, lembrar),
  fontesSistema: () => ipcRenderer.invoke('fontes:sistema'),
  lerFonte: c => ipcRenderer.invoke('fontes:ler', c),
  importarSvg: () => ipcRenderer.invoke('arquivo:importarSvg'),
  existe: c => ipcRenderer.invoke('arquivo:existe', c),
  listarProjetos: () => ipcRenderer.invoke('projetos:listar'),
  locaisPastas: () => ipcRenderer.invoke('pasta:locais'),
  listarPasta: dir => ipcRenderer.invoke('pasta:listar', dir),
  salvar: (caminho, texto) => ipcRenderer.invoke('arquivo:salvar', caminho, texto),
  salvarComo: (sugestao, texto) => ipcRenderer.invoke('arquivo:salvarComo', sugestao, texto),
  exportar: (sugestao, bytes, ext, rotulo) => ipcRenderer.invoke('arquivo:exportar', sugestao, bytes, ext, rotulo),
  exportarVarios: arquivos => ipcRenderer.invoke('arquivo:exportarVarios', arquivos),
  importar: () => ipcRenderer.invoke('arquivo:importar'),
  listarPecas: () => ipcRenderer.invoke('pecas:listar'),
  salvarPeca: (nome, texto) => ipcRenderer.invoke('pecas:salvar', nome, texto),
  abrirPastaPecas: () => ipcRenderer.invoke('pecas:abrirPasta'),
  arquivoInicial: () => ipcRenderer.invoke('app:arquivoInicial'),
  versao: () => ipcRenderer.invoke('app:versao'),
  definirIdioma: l => ipcRenderer.send('app:idioma', l),
  informarEstado: s => ipcRenderer.send('app:estado', s),
  aoSalvarEFechar: cb => ipcRenderer.on('app:salvarEFechar', cb),
  perguntarSalvar: () => ipcRenderer.invoke('app:perguntarSalvar'),
  fecharAgora: () => ipcRenderer.send('app:fecharAgora'),
});
